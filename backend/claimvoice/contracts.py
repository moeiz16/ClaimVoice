"""In-process interfaces between the voice/dialogue/ML side and the platform side (docs/API_CONTRACT.md Part 3).

Ownership rule: the voice runtime owns a live call's state in memory and is the only source of call facts; the
platform owns the database, the event stream (SSE), audit and every HTTP endpoint. The voice runtime never touches
the database: it reports facts through `CallSink`. The platform never drives the dialogue: it sends supervisor
actions through `LineControl`. Policy data, scripts and settings reach the dialogue through `PolicyDirectory` and
`OrgPlaybook`. At hang-up the platform calls `TriageScorer` and `CallScorer`, which the ML and QA modules implement.

Values are plain frozen dataclasses (no ORM objects cross this line). Times are aware UTC datetimes from
`claimvoice.clock`. Offsets inside a call (`at_ms`) are milliseconds since the call was answered, from a monotonic
clock.
"""

from __future__ import annotations

from collections.abc import Mapping, Sequence
from dataclasses import dataclass, field
from datetime import date
from enum import StrEnum
from typing import Any, Protocol, runtime_checkable


class Speaker(StrEnum):
    CALLER = "caller"
    LINE = "line"  # the ClaimVoice voice line
    PERSON = "person"  # a human agent or supervisor who took the call
    SYSTEM = "system"  # notices ("Recording paused", "Transferred to Dana")


class CallMode(StrEnum):
    VOICE = "voice"  # caller audio to server STT; line audio from server TTS
    BROWSER_SPEECH = "browser_speech"  # browser recognises and speaks; text on the data channel (offline default)
    TYPED = "typed"  # text only (accessibility "read instead", or no microphone)


class HandoffReason(StrEnum):
    CALLER_ASKED = "caller_asked"
    URGENT_SAFETY = "urgent_safety"
    DISTRESS = "distress"
    LOW_CONFIDENCE = "low_confidence"
    IDENTITY_UNVERIFIED = "identity_unverified"
    TOOL_FAILED = "tool_failed"
    CONSENT_REFUSED = "consent_refused"
    SUPERVISOR = "supervisor"  # a supervisor took the call


class FlagKind(StrEnum):
    URGENT_SAFETY = "urgent_safety"
    DISTRESS = "distress"
    CARD_NUMBER_REMOVED = "card_number_removed"
    LOW_CONFIDENCE = "low_confidence"
    SIU_SIGNAL = "siu_signal"  # a fraud indicator was heard (shown to SIU and supervisors only; never to the caller)
    CONSENT_REFUSED = "consent_refused"
    SURGE = "surge"  # the loss matches an active catastrophe event
    LANGUAGE_SWITCHED = "language_switched"


# ---------------------------------------------------------------- facts the voice runtime reports (CallSink)


@dataclass(frozen=True, slots=True)
class CallOpened:
    call_id: str
    org_id: str
    mode: CallMode
    language: str  # "en" | "fr"
    channel: str  # "browser" | "demo_line" | "test"
    caller_phone: str | None  # E.164 when known (typed in the demo, or caller id); stored masked except for SMS
    region_hint: str | None  # ISO 3166-2 from caller id / demo picker; decides the consent rule until verified
    scenario: str | None = None  # scripted demo caller key, when the call is a scripted demo
    started_by_user_id: str | None = None


@dataclass(frozen=True, slots=True)
class TurnRecord:
    turn_id: str  # generated by the voice runtime (uuid4), so slots can reference it before it is persisted
    seq: int  # 1-based, per call
    speaker: Speaker
    text: str  # already redacted
    language: str
    at_ms: int
    end_ms: int
    stage: str
    confidence: float | None = None  # caller turns only
    interrupted: bool = False  # line turn cut short by barge-in
    redactions: int = 0  # card numbers removed from this turn
    retained: bool = True  # False when recording consent was refused: purged at call end, never shown later
    speaker_name: str | None = None  # for PERSON turns


@dataclass(frozen=True, slots=True)
class SlotRecord:
    key: str  # claim-file field key (docs/API_CONTRACT.md §5.4)
    value: Any
    display: str
    confidence: float
    source: str  # "heard" | "policy_record" | "tool" | "person"
    turn_id: str | None
    span: tuple[int, int] | None  # character offsets into that turn's text
    confirmed: bool = False  # confirmed by the caller at read-back
    corrects: bool = False


@dataclass(frozen=True, slots=True)
class StageChange:
    stage: str
    previous: str
    event: str
    at_ms: int


@dataclass(frozen=True, slots=True)
class CallFlag:
    kind: FlagKind
    detail: str  # plain words for the supervisor ("Caller mentioned a smell of gas")
    at_ms: int
    turn_id: str | None = None


@dataclass(frozen=True, slots=True)
class ConsentRecord:
    rule: str  # "one_party" | "all_party"
    region: str
    announced_at_ms: int
    answer: str  # "given" | "refused" | "not_required"
    recording: bool  # whether audio and transcript are being kept
    turn_id: str | None = None


@dataclass(frozen=True, slots=True)
class ToolCallRecord:
    tool: str
    ok: bool
    elapsed_ms: float
    budget_ms: int
    timed_out: bool
    at_ms: int
    summary: str  # "Policy LM-AB-204118 found" (no personal data beyond what the claim file shows)


@dataclass(frozen=True, slots=True)
class TurnLatency:
    """Per caller turn: end of caller speech -> first line audio (or first caption in browser_speech mode)."""

    turn_id: str
    stt_ms: float
    understand_ms: float
    tools_ms: float
    plan_ms: float
    tts_first_audio_ms: float
    total_ms: float


@dataclass(frozen=True, slots=True)
class HandoffTicket:
    handoff_id: str
    position: int  # place in the hand-off tray
    expected_wait_seconds: int | None


@dataclass(frozen=True, slots=True)
class CallClosing:
    reason: str  # "completed" | "caller_hung_up" | "silence" | "handed_off_completed" | "ended_by_person" | "error"
    ended_at_ms: int
    final_stage: str
    recording_path: str | None  # relative to RECORDINGS_DIR; None when not recorded
    recording_seconds: float | None
    summary: str  # read-back summary in the call's language
    summary_en: str | None  # English summary for adjusters when the call was in French
    turn_count: int
    latency_p95_ms: float | None


@runtime_checkable
class CallSink(Protocol):
    """Implemented by the platform (persists, audits where needed, publishes SSE). Every method must return within
    20 ms p95 (buffer writes if needed); the voice runtime awaits them on the turn path."""

    async def call_opened(self, call: CallOpened) -> None: ...
    async def consent(self, call_id: str, consent: ConsentRecord) -> None: ...
    async def turn(self, call_id: str, turn: TurnRecord) -> None: ...
    async def partial(self, call_id: str, speaker: Speaker, text: str) -> None:
        """Interim caller text for listeners. Never persisted."""
        ...

    async def slot(self, call_id: str, slot: SlotRecord) -> None: ...
    async def stage(self, call_id: str, change: StageChange) -> None: ...
    async def flag(self, call_id: str, flag: CallFlag) -> None: ...
    async def tool_called(self, call_id: str, record: ToolCallRecord) -> None: ...
    async def latency(self, call_id: str, sample: TurnLatency) -> None: ...
    async def caller_identified(self, call_id: str, policy_id: str, holder_id: str, region: str) -> None: ...
    async def photo_link_sent(self, call_id: str, to_masked: str, link_token: str) -> None: ...
    async def handoff_requested(self, call_id: str, reason: HandoffReason, detail: str) -> HandoffTicket: ...
    async def call_closed(self, call_id: str, closing: CallClosing) -> None:
        """Platform then: purges unretained turns, creates the claim, runs TriageScorer and CallScorer, opens an SIU
        referral when indicated, publishes `line.closed` and `claim.created`."""
        ...


# ---------------------------------------------------------------- supervisor actions (LineControl)


@runtime_checkable
class LineControl(Protocol):
    """Implemented by the voice runtime. The platform calls it from the HTTP endpoints after RBAC and audit."""

    def is_live(self, call_id: str) -> bool: ...
    async def whisper(self, call_id: str, text: str, *, from_name: str) -> None:
        """A private note to the line (never spoken). The engine may add a question to the current stage."""
        ...

    async def take_over(self, call_id: str, *, user_id: str, name: str) -> None:
        """The line stops speaking and stops asking; the person's typed or spoken words reach the caller."""
        ...

    async def say_as_person(self, call_id: str, text: str, *, user_id: str, name: str) -> str:
        """Typed take-over: speak `text` to the caller as the person; returns the turn id."""
        ...

    async def hand_back(self, call_id: str, *, user_id: str) -> None: ...
    async def hang_up(self, call_id: str, *, reason: str, by_user_id: str | None) -> None: ...


# ---------------------------------------------------------------- data the dialogue needs (platform implements)


@dataclass(frozen=True, slots=True)
class PolicyMatch:
    policy_id: str
    holder_id: str
    policy_number: str
    holder_name: str
    line: str  # "auto" | "property"
    region: str
    status: str  # "active" | "lapsed" | "cancelled"
    preferred_language: str
    phone_on_file_masked: str | None
    insured_items: Sequence[Mapping[str, Any]] = ()  # [{"id", "kind", "label"}] e.g. "2021 Toyota RAV4"


@dataclass(frozen=True, slots=True)
class CoverageLine:
    key: str  # "collision", "comprehensive", "sewer_backup", ...
    label: str
    included: bool
    deductible: float | None
    limit: float | None


@dataclass(frozen=True, slots=True)
class CoverageSummary:
    policy_id: str
    loss_type: str
    in_force_on_loss_date: bool
    lines: Sequence[CoverageLine]
    plain_words: Mapping[str, str]  # {"en": "...", "fr": "..."}: what the line may say. Never a claim decision.


@runtime_checkable
class PolicyDirectory(Protocol):
    async def find_policy(
        self,
        org_id: str,
        *,
        policy_number: str | None = None,
        phone: str | None = None,
        full_name: str | None = None,
        postal_code: str | None = None,
    ) -> PolicyMatch | None: ...
    async def verify_identity(
        self, org_id: str, policy_id: str, *, date_of_birth: date | None = None, postal_code: str | None = None
    ) -> bool: ...
    async def coverage(self, org_id: str, policy_id: str, loss_type: str, loss_date: date) -> CoverageSummary: ...
    async def prior_claims(self, org_id: str, holder_id: str, *, months: int = 36) -> int: ...


@dataclass(frozen=True, slots=True)
class ScriptQuestion:
    slot_key: str
    kind: str  # SlotSpec.kind
    prompt: Mapping[str, str]  # {"en": ..., "fr": ...}
    required: bool = True
    when: str | None = None  # simple condition on filled slots, e.g. "other_party_involved == true"
    choices: Sequence[str] = ()


@dataclass(frozen=True, slots=True)
class Script:
    loss_type: str
    version: int
    questions: Sequence[ScriptQuestion]


@dataclass(frozen=True, slots=True)
class ConsentRule:
    region: str
    rule: str  # "one_party" | "all_party"
    announcement: Mapping[str, str]  # {"en": ..., "fr": ...}


@dataclass(frozen=True, slots=True)
class HandoffRules:
    low_confidence_turns: int = 2
    distress_threshold: float = 0.7
    identity_attempts: int = 3
    offer_person_on_consent_refusal: bool = True
    max_wait_seconds: int = 90  # then offer a call-back and finish the claim file with the line
    french_first_regions: Sequence[str] = ("CA-QC",)


@runtime_checkable
class OrgPlaybook(Protocol):
    async def script(self, org_id: str, loss_type: str) -> Script: ...
    async def consent_rule(self, org_id: str, region: str) -> ConsentRule: ...
    async def handoff_rules(self, org_id: str) -> HandoffRules: ...
    async def active_surge(self, org_id: str, region: str) -> Mapping[str, Any] | None: ...


# ---------------------------------------------------------------- at hang-up (ML and QA implement)


@dataclass(frozen=True, slots=True)
class TriageInput:
    """Everything the routing models may use. No protected attributes: language, region and age band travel in
    `fairness_groups` for fairness reporting only and never reach a model."""

    claim_id: str
    org_id: str
    line: str
    loss_type: str
    features: Mapping[str, float | int | str | bool | None]  # docs/API_CONTRACT.md §6.2 feature list
    fairness_groups: Mapping[str, str] = field(
        default_factory=dict
    )  # {"region": ..., "language": ..., "age_band": ...}


@dataclass(frozen=True, slots=True)
class Reason:
    feature: str
    text: Mapping[str, str]  # {"en": "Reported 41 days after the loss", "fr": ...}
    direction: str  # "raises" | "lowers"
    weight: float  # |SHAP| share, 0..1


@dataclass(frozen=True, slots=True)
class RoutingDecision:
    route: str  # "fast_track" | "adjuster" | "special_investigation"
    severity_probability: float  # calibrated P(large or complex loss)
    severity_band: str  # "low" | "medium" | "high"
    fraud_score: float  # calibrated 0..1
    fraud_band: str  # "low" | "elevated" | "high"
    siu_referral: bool
    reasons: Sequence[Reason]  # top 3-5, plain words
    fraud_indicators: Sequence[Reason]  # shown to SIU only
    rules_applied: Sequence[str]  # e.g. "Injury reported: never fast-tracked"
    model_versions: Mapping[str, str]  # {"severity": "3", "fraud": "2"}


@runtime_checkable
class TriageScorer(Protocol):
    def score(self, item: TriageInput) -> RoutingDecision: ...


@dataclass(frozen=True, slots=True)
class QaItemResult:
    key: str
    passed: bool | None  # None = not applicable on this call
    points: float
    max_points: float
    evidence_turn_ids: Sequence[str]
    note: str
    method: str  # "rule" | "language_check"


@dataclass(frozen=True, slots=True)
class QaResult:
    score: float  # 0..100
    band: str  # "good" | "needs_attention" | "failed"
    items: Sequence[QaItemResult]
    needs_review: bool
    scorer_version: str


@runtime_checkable
class CallScorer(Protocol):
    def score(
        self, turns: Sequence[TurnRecord], events: Sequence[Mapping[str, Any]], slots: Mapping[str, SlotRecord]
    ) -> QaResult: ...


# ---------------------------------------------------------------- an in-memory sink for voice/dialogue tests


@dataclass
class MemoryCallSink:
    """Records every fact in order. Used by dialogue tests, the eval harness and the latency runner."""

    events: list[tuple[str, str, Any]] = field(default_factory=list)
    _handoffs: int = 0

    async def call_opened(self, call: CallOpened) -> None:
        self.events.append(("call_opened", call.call_id, call))

    async def consent(self, call_id: str, consent: ConsentRecord) -> None:
        self.events.append(("consent", call_id, consent))

    async def turn(self, call_id: str, turn: TurnRecord) -> None:
        self.events.append(("turn", call_id, turn))

    async def partial(self, call_id: str, speaker: Speaker, text: str) -> None:
        self.events.append(("partial", call_id, (speaker, text)))

    async def slot(self, call_id: str, slot: SlotRecord) -> None:
        self.events.append(("slot", call_id, slot))

    async def stage(self, call_id: str, change: StageChange) -> None:
        self.events.append(("stage", call_id, change))

    async def flag(self, call_id: str, flag: CallFlag) -> None:
        self.events.append(("flag", call_id, flag))

    async def tool_called(self, call_id: str, record: ToolCallRecord) -> None:
        self.events.append(("tool", call_id, record))

    async def latency(self, call_id: str, sample: TurnLatency) -> None:
        self.events.append(("latency", call_id, sample))

    async def caller_identified(self, call_id: str, policy_id: str, holder_id: str, region: str) -> None:
        self.events.append(("identified", call_id, (policy_id, holder_id, region)))

    async def photo_link_sent(self, call_id: str, to_masked: str, link_token: str) -> None:
        self.events.append(("photo_link", call_id, (to_masked, link_token)))

    async def handoff_requested(self, call_id: str, reason: HandoffReason, detail: str) -> HandoffTicket:
        self._handoffs += 1
        self.events.append(("handoff", call_id, (reason, detail)))
        return HandoffTicket(f"handoff-{self._handoffs}", self._handoffs, 60)

    async def call_closed(self, call_id: str, closing: CallClosing) -> None:
        self.events.append(("closed", call_id, closing))

    def of(self, kind: str) -> list[Any]:
        return [payload for k, _, payload in self.events if k == kind]

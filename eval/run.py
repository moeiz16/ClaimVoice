"""Evaluation harness: runs every gate suite and writes eval/RESULTS.md and eval/results.json.

Suites (one module each in eval/suites/, exposing `run() -> Report`):
  dialogue  task completion and value accuracy on the scripted callers in eval/callers/ (EN/FR, interruptions,
            corrections, off-script turns), safety triggers caught, consent always first, 0 card numbers stored
  latency   per-turn time from end of caller speech to first line audio, with fakes (p50/p95; gate p95 < 800 ms)
  models    the routing checks vs baselines (AUC, PR-AUC, Brier, ECE), SHAP stability, fairness gaps, PSI drift
  qa        call-quality scorer agreement with reviewed calls

Run: make eval (from backend/: ../eval/run.py). Exit code 1 when any gate fails. No run timestamps are written.
"""

from __future__ import annotations

import importlib.util
import json
import os
import sys
from dataclasses import asdict
from pathlib import Path

EVAL = Path(__file__).resolve().parent
sys.path.insert(0, str(EVAL / "suites"))
os.environ.setdefault("CLAIMVOICE_DEMO_TODAY", "off")
os.environ.setdefault("LLM_FAKE", "true")
os.environ.setdefault("MLFLOW_DISABLE_AGENT_HINT", "1")

from common import Gate, Report  # noqa: E402

SUITES = ("dialogue", "latency", "models", "qa")
TITLES = {
    "dialogue": "Dialogue (scripted callers)",
    "latency": "Response time per turn",
    "models": "Routing checks",
    "qa": "Call quality scorer",
}


def load(name: str):
    path = EVAL / "suites" / f"{name}.py"
    if not path.exists():
        return None
    spec = importlib.util.spec_from_file_location(f"eval_suite_{name}", path)
    if spec is None or spec.loader is None:
        raise ImportError(path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def main(argv: list[str]) -> int:
    only = [a for a in argv[1:] if a in SUITES] or list(SUITES)
    reports: dict[str, Report] = {}
    missing: list[str] = []
    for name in only:
        module = load(name)
        if module is None:
            missing.append(name)
            continue
        out = module.run()
        reports[name] = out if isinstance(out, Report) else Report(gates=list(out))
    gates: list[Gate] = [g for r in reports.values() for g in r.gates]
    lines = [
        "# Evaluation results",
        "",
        "Generated by `make eval`. Offline: deterministic fakes for every cloud service, synthetic data, fixed seeds.",
        "",
        "## Gates",
        "",
        "| Suite | Gate | Value | Limit | Result |",
        "|---|---|---:|---:|---|",
    ]
    for g in gates:
        op = "≥" if g.direction == "min" else "≤"
        lines.append(f"| {g.suite} | {g.label} | {g.value:.3f} | {op} {g.limit:g} | {'pass' if g.passed else 'FAIL'} |")
    for name, r in reports.items():
        if r.lines:
            lines += ["", f"## {TITLES[name]}", "", *r.lines]
    if missing:
        lines += ["", "Suites not implemented yet: " + ", ".join(missing) + "."]
    if only == list(SUITES):
        (EVAL / "RESULTS.md").write_text("\n".join(lines) + "\n")
        (EVAL / "results.json").write_text(
            json.dumps(
                {
                    "gates": [{**asdict(g), "passed": g.passed} for g in gates],
                    "details": {k: r.data for k, r in reports.items()},
                },
                indent=2,
                ensure_ascii=False,
                default=str,
            )
            + "\n"
        )
    failed = [g for g in gates if not g.passed]
    for g in failed:
        print(f"FAIL {g.suite}: {g.label} = {g.value:.4f} (limit {g.limit})")
    print(f"{len(gates)} gates, {len(failed)} failed" + (f"; missing suites: {', '.join(missing)}" if missing else ""))
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))

"""Evaluation harness: runs every gate suite and writes eval/RESULTS.md and eval/results.json.

Suites (one module each in eval/suites/, exposing `run() -> list[Gate]`):
  dialogue  task completion and slot accuracy on the scripted callers in eval/callers/ (EN/FR, interruptions,
            corrections, off-script turns), safety triggers caught, consent always first, 0 card numbers stored
  latency   per-turn time from end of caller speech to first line audio, with fakes (p50/p95; gate p95 < 800 ms)
  models    severity and fraud models vs baselines (AUC, PR-AUC, Brier, ECE), SHAP stability, fairness gaps, PSI
  qa        call-quality scorer agreement with labelled calls

Run: make eval (from backend/: ../eval/run.py). Exit code 1 when any gate fails. No run timestamps are written.
"""

from __future__ import annotations

import importlib.util
import json
import sys
from dataclasses import asdict, dataclass
from pathlib import Path

EVAL = Path(__file__).resolve().parent
SUITES = ("dialogue", "latency", "models", "qa")


@dataclass(frozen=True)
class Gate:
    suite: str
    key: str
    label: str
    value: float
    limit: float
    direction: str  # "min" (value >= limit passes) or "max" (value <= limit passes)

    @property
    def passed(self) -> bool:
        return self.value >= self.limit if self.direction == "min" else self.value <= self.limit


def load(name: str):
    path = EVAL / "suites" / f"{name}.py"
    if not path.exists():
        return None
    spec = importlib.util.spec_from_file_location(f"eval_suite_{name}", path)
    if spec is None or spec.loader is None:
        raise ImportError(path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def main() -> int:
    gates: list[Gate] = []
    missing: list[str] = []
    for name in SUITES:
        module = load(name)
        if module is None:
            missing.append(name)
            continue
        gates.extend(module.run())
    lines = ["# Evaluation results", "", "Generated by `make eval`. Offline: fakes for every cloud service.", ""]
    lines += ["| Suite | Gate | Value | Limit | Result |", "|---|---|---:|---:|---|"]
    for g in gates:
        op = "≥" if g.direction == "min" else "≤"
        lines.append(f"| {g.suite} | {g.label} | {g.value:.3f} | {op} {g.limit:g} | {'pass' if g.passed else 'FAIL'} |")
    if missing:
        lines += ["", "Suites not implemented yet: " + ", ".join(missing) + "."]
    (EVAL / "RESULTS.md").write_text("\n".join(lines) + "\n")
    (EVAL / "results.json").write_text(
        json.dumps([{**asdict(g), "passed": g.passed} for g in gates], indent=2, ensure_ascii=False) + "\n"
    )
    failed = [g for g in gates if not g.passed]
    print(f"{len(gates)} gates, {len(failed)} failed" + (f"; missing suites: {', '.join(missing)}" if missing else ""))
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
